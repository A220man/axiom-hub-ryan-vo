"""Design Document Generator Service."""

from typing import Dict, Any, Optional
from datetime import datetime, timezone


class DesignDocumentGenerator:
    """Generates DESIGN.md files from design analysis results."""

    SECTIONS = [
        "overview",
        "design-principles",
        "color-palette",
        "typography",
        "spacing",
        "component-patterns",
        "usage-guidelines",
        "tokens-reference",
    ]

    def __init__(self, analysis: Dict[str, Any], custom_content: Optional[Dict[str, Any]] = None):
        self.analysis = analysis
        self.custom_content = custom_content or {}

    def generate(self, include_llm_explanation: bool = False) -> str:
        """Generate the full DESIGN.md content."""
        lines = []

        # Header
        lines.append("# Design System Documentation")
        lines.append("")
        lines.append(f"> Generated on {datetime.now(timezone.utc).strftime('%Y-%m-%d %H:%M:%S')} UTC")
        lines.append(f"> Source: {self.analysis.get('source_path', 'Unknown')}")
        lines.append("")

        # Table of Contents
        lines.append("## Table of Contents")
        lines.append("")
        for i, section in enumerate(self.SECTIONS, 1):
            lines.append(f"{i}. [{section.replace('-', ' ').title()}](#{section})")
        lines.append("")

        # Sections
        lines.append(self._generate_overview())
        lines.append(self._generate_design_principles())
        lines.append(self._generate_color_palette())
        lines.append(self._generate_typography())
        lines.append(self._generate_spacing())
        lines.append(self._generate_component_patterns())
        lines.append(self._generate_usage_guidelines())
        lines.append(self._generate_tokens_reference())

        # LLM Explanation (advisory)
        if include_llm_explanation and self.analysis.get("llm_explanation"):
            lines.append("")
            lines.append("---")
            lines.append("")
            lines.append("## AI-Generated Explanation (Advisory)")
            lines.append("")
            lines.append("> **Note:** The following explanation was generated by an LLM and is provided for advisory purposes only. It may contain inaccuracies and should not be treated as authoritative.")
            lines.append("")
            lines.append(self.analysis["llm_explanation"])

        return "\n".join(lines)

    def _generate_overview(self) -> str:
        """Generate overview section."""
        lines = ["## Overview", ""]
        lines.append("This document describes the design system extracted from the codebase.")
        lines.append("")
        raw = self.analysis.get("raw_findings", {})
        lines.append(f"- **Files Scanned**: {raw.get('files_scanned', 0)}")
        lines.append(f"- **CSS/SCSS Files**: {raw.get('css_files', 0)}")
        lines.append(f"- **Component Files**: {raw.get('component_files', 0)}")
        lines.append(f"- **Color Tokens Found**: {raw.get('color_tokens_found', 0)}")
        lines.append(f"- **Spacing Tokens Found**: {raw.get('spacing_tokens_found', 0)}")
        lines.append(f"- **Typography Tokens Found**: {raw.get('typography_tokens_found', 0)}")
        lines.append("")
        return "\n".join(lines)

    def _generate_design_principles(self) -> str:
        """Generate design principles section."""
        lines = ["## Design Principles", ""]
        lines.append("The following principles guide this design system:")
        lines.append("")
        lines.append("1. **Consistency** - Use design tokens for all visual properties")
        lines.append("2. **Scalability** - Tokens should work across all component sizes and contexts")
        lines.append("3. **Accessibility** - Color contrasts meet WCAG AA minimum standards")
        lines.append("4. **Maintainability** - Single source of truth for all design decisions")
        lines.append("5. **Performance** - Minimize CSS bundle size through token reuse")
        lines.append("")
        custom = self.custom_content.get("principles")
        if custom:
            lines.append("### Custom Principles")
            lines.append("")
            for principle in custom:
                lines.append(f"- {principle}")
            lines.append("")
        return "\n".join(lines)

    def _generate_color_palette(self) -> str:
        """Generate color palette section."""
        lines = ["## Color Palette", ""]
        palette = self.analysis.get("color_palette", {})
        families = palette.get("families", {})
        semantic = palette.get("semantic", {})

        if families:
            lines.append("### Color Families")
            lines.append("")
            for family, shades in families.items():
                lines.append(f"#### {family.title()}")
                lines.append("")
                lines.append("| Shade | Value |")
                lines.append("|-------|-------|")
                for shade, value in sorted(shades.items()):
                    lines.append(f"| {shade} | `{value}` |")
                lines.append("")
        else:
            lines.append("*No custom color tokens found. Using defaults.*")
            lines.append("")

        lines.append("### Semantic Colors")
        lines.append("")
        lines.append("| Role | Value |")
        lines.append("|------|-------|")
        for role, value in semantic.items():
            lines.append(f"| {role.title()} | `{value}` |")
        lines.append("")
        return "\n".join(lines)

    def _generate_typography(self) -> str:
        """Generate typography section."""
        lines = ["## Typography", ""]
        type_scale = self.analysis.get("type_scale", {})
        base = type_scale.get("base", "1rem")
        scale = type_scale.get("scale", {})
        font_families = type_scale.get("font_families", {})
        line_heights = type_scale.get("line_heights", {})
        font_weights = type_scale.get("font_weights", {})

        lines.append(f"**Base Font Size**: `{base}`")
        lines.append("")

        lines.append("### Type Scale")
        lines.append("")
        lines.append("| Token | Size |")
        lines.append("|-------|------|")
        for token, size in scale.items():
            lines.append(f"| `{token}` | `{size}` |")
        lines.append("")

        lines.append("### Font Families")
        lines.append("")
        lines.append("| Family | Font Stack |")
        lines.append("|--------|------------|")
        for family, stack in font_families.items():
            lines.append(f"| {family} | `{stack}` |")
        lines.append("")

        lines.append("### Line Heights")
        lines.append("")
        lines.append("| Token | Value |")
        lines.append("|-------|-------|")
        for token, value in line_heights.items():
            lines.append(f"| `{token}` | `{value}` |")
        lines.append("")

        lines.append("### Font Weights")
        lines.append("")
        lines.append("| Token | Weight |")
        lines.append("|-------|--------|")
        for token, weight in font_weights.items():
            lines.append(f"| `{token}` | `{weight}` |")
        lines.append("")
        return "\n".join(lines)

    def _generate_spacing(self) -> str:
        """Generate spacing section."""
        lines = ["## Spacing", ""]
        spacing = self.analysis.get("spacing", {})
        base = spacing.get("base", "0.25rem")
        scale = spacing.get("scale", {})

        lines.append(f"**Base Unit**: `{base}`")
        lines.append("")
        lines.append("### Spacing Scale")
        lines.append("")
        lines.append("| Token | Value |")
        lines.append("|-------|-------|")
        for token, value in sorted(scale.items(), key=lambda x: self._spacing_sort_key(x[0])):
            lines.append(f"| `{token}` | `{value}` |")
        lines.append("")
        return "\n".join(lines)

    def _spacing_sort_key(self, token: str) -> tuple:
        """Sort spacing tokens numerically."""
        try:
            return (0, int(token))
        except ValueError:
            return (1, token)

    def _generate_component_patterns(self) -> str:
        """Generate component patterns section."""
        lines = ["## Component Patterns", ""]
        patterns = self.analysis.get("component_patterns", {})
        components_found = patterns.get("components_found", 0)
        common_props = patterns.get("common_props", {})
        styling_approaches = patterns.get("styling_approaches", {})
        component_names = patterns.get("component_names", [])

        lines.append(f"**Components Found**: {components_found}")
        lines.append("")

        if component_names:
            lines.append("### Component Inventory")
            lines.append("")
            for name in component_names[:20]:
                lines.append(f"- `{name}`")
            if len(component_names) > 20:
                lines.append(f"- *...and {len(component_names) - 20} more*")
            lines.append("")

        if common_props:
            lines.append("### Common Props")
            lines.append("")
            lines.append("| Prop | Frequency |")
            lines.append("|------|-----------|")
            for prop, count in list(common_props.items())[:15]:
                lines.append(f"| `{prop}` | {count} |")
            lines.append("")

        if styling_approaches:
            lines.append("### Styling Approaches")
            lines.append("")
            lines.append("| Approach | Components |")
            lines.append("|----------|------------|")
            for approach, count in styling_approaches.items():
                lines.append(f"| {approach} | {count} |")
            lines.append("")
        return "\n".join(lines)

    def _generate_usage_guidelines(self) -> str:
        """Generate usage guidelines section."""
        lines = ["## Usage Guidelines", ""]
        lines.append("### Do's")
        lines.append("")
        lines.append("- Always use design tokens instead of hardcoded values")
        lines.append("- Extend the system through token additions, not overrides")
        lines.append("- Test components at all type scale and spacing combinations")
        lines.append("- Maintain semantic color usage (primary, success, warning, error)")
        lines.append("")
        lines.append("### Don'ts")
        lines.append("")
        lines.append("- Don't hardcode pixel values for colors, spacing, or typography")
        lines.append("- Don't create one-off component variants without token support")
        lines.append("- Don't mix styling approaches within the same component")
        lines.append("")
        custom = self.custom_content.get("guidelines")
        if custom:
            lines.append("### Custom Guidelines")
            lines.append("")
            for guideline in custom:
                lines.append(f"- {guideline}")
            lines.append("")
        return "\n".join(lines)

    def _generate_tokens_reference(self) -> str:
        """Generate tokens reference section."""
        lines = ["## Tokens Reference", ""]
        lines.append("Complete reference of all design tokens in this system.")
        lines.append("")

        # Color tokens
        palette = self.analysis.get("color_palette", {})
        families = palette.get("families", {})
        if families:
            lines.append("### Color Tokens")
            lines.append("")
            for family, shades in families.items():
                lines.append(f"#### {family}")
                lines.append("")
                for shade, value in sorted(shades.items()):
                    lines.append(f"- `--color-{family}-{shade}`: `{value}`")
                lines.append("")

        # Spacing tokens
        spacing = self.analysis.get("spacing", {})
        scale = spacing.get("scale", {})
        if scale:
            lines.append("### Spacing Tokens")
            lines.append("")
            for token, value in sorted(scale.items(), key=lambda x: self._spacing_sort_key(x[0])):
                lines.append(f"- `--spacing-{token}`: `{value}`")
            lines.append("")

        # Typography tokens
        type_scale = self.analysis.get("type_scale", {})
        scale = type_scale.get("scale", {})
        if scale:
            lines.append("### Typography Tokens")
            lines.append("")
            for token, value in scale.items():
                lines.append(f"`--font-size-{token}`: `{value}`")
            lines.append("")

        return "\n".join(lines)